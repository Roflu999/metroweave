export function emptyNetwork(city?: {
  city: string;
  country: string;
  lat: number;
  lng: number;
}): Network {
  return {
    version: 1,
    id: globalThis.crypto?.randomUUID?.() ?? `network-${Date.now()}`,
    name: city ? `${city.city} — new network` : "Untitled network",
    city: city?.city ?? "",
    country: city?.country ?? "",
    description:
      "A new transit design. Add stations, connect service patterns, and shape your city.",
    stations: [],
    routes: [],
    services: [],
    sources: [],
    dataStatus: "custom",
    center: city ? [city.lat, city.lng] : [51.5074, -0.1278],
    zoom: 12,
    updatedAt: new Date().toISOString(),
  };
}
