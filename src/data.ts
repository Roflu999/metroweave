function service(
  id: string,
  routeId: string,
  name: string,
  stationIds: string[],
  extra: Partial<Service> = {},
): Service {
  return {
    id,
    routeId,
    name,
    kind: "local",
    stationIds,
    skippedStationIds: [],
    waypoints: {},
    loop: false,
    direction: "both",
    headway: 5,
    speed: 42,
    dwell: 30,
    ...extra,
  };
}

